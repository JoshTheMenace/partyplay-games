import type { Card, CardKind, Figure } from './types';

/**
 * Stock card banks (server only). Ids come from list position (i001, g001, m001) and are stable forever, because voice
 * recordings and tests key on them: never reorder or delete a row. Retire a card by replacing its row with null (a gap)
 * and append new cards at the end. S marks a spicy card, which the family setting leaves out.
 */
type Row = string | readonly [string, Figure] | readonly [string, Figure | null, typeof S] | null;
const S = 1;
const build = (kind: CardKind, rows: readonly Row[]): readonly Card[] => rows.flatMap((row, i) => {
  if (!row) return [];
  const [text, figure, spicy] = typeof row === 'string' ? [row] : row;
  const card: Card = { id: `${kind[0]}${String(i + 1).padStart(3, '0')}`, kind, text };
  if (figure) card.figure = figure;
  if (spicy) card.spicy = true;
  return [card];
});

